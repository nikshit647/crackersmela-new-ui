async function request(client, action, data, options = {}) {
  const method = options.method || (data ? 'POST' : 'GET');
  const url = options.path || (method === 'GET' ? '/customer-auth.php?a=' + action : '/customer-auth.php');
  const headers = { Cookie: client.cookie, Origin: base, 'Content-Type': 'application/json', ...options.headers };
  if (data && options.csrf !== false) headers['X-CSRF-Token'] = client.csrf;
  const res = await fetch(base + url, { method, headers, body: method === 'GET' ? undefined : (options.raw ?? JSON.stringify({ a: action, ...data })) });
  const cookies = res.headers.getSetCookie();
  for (const cookie of cookies) if (cookie.startsWith('cm_staff=')) client.cookie = cookie.split(';')[0];
  const json = await res.json();
  if (json.csrfToken) client.csrf = json.csrfToken;
  return { status: res.status, body: json, cookies };
}
